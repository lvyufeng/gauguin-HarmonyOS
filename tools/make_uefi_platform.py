def parse_uefiplat(path):
    """Return (memory_map, register_map, config_params) from uefiplat.cfg.

    The two map sections share one line format:
        0xADDR, 0xSIZE, "Label", HobOption, ResourceType, ResourceAttribute,
        MemoryType, ArmAttribute
    """
    memory, registers, params = [], [], []
    section = None
    for raw in open(path, encoding="utf-8", errors="replace"):
        line = raw.strip()
        if line.startswith("[") and line.endswith("]"):
            section = line.strip("[]")
            continue
        if not line or line.startswith("#"):
            continue
        if section in ("MemoryMap", "RegisterMap"):
            m = re.match(
                r'^(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*"([^"]*)"\s*,\s*'
                r'(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*(?:,\s*(\w+))?', line)
            if not m:
                continue
            addr, size, label, hob, rtype, rattr, mtype, armattr = m.groups()
            entry = dict(addr=int(addr, 16), size=int(size, 16), label=label,
                         hob=hob, rtype=rtype, rattr=rattr, mtype=mtype,
                         armattr=armattr or "NS_DEVICE")
            (memory if section == "MemoryMap" else registers).append(entry)
        elif section == "ConfigParameters":
            m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.+?)\s*$', line)
            if not m:
                continue
            key, val = m.groups()
            if val.startswith('"'):
                continue                      # strings are not map entries
            try:
                params.append((key, int(val, 0)))
            except ValueError:
                pass
    return memory, registers, params


def emit_memmap(memory, registers, out):
    w = out.write
    w(LICENSE)
    w('#include <Library/MemoryMapLib.h>\n\n')
    w(GEN_NOTE)
    w("STATIC\nEFI_MEMORY_REGION_DESCRIPTOR\ngMemoryDescriptor[] = {\n")
    w("  // Name, Address, Length, HobOption, ResourceType, ResourceAttribute, MemoryType, ArmAttribute\n")
    w("\n  // DDR Regions\n")
    for e in memory:
        w(f'  {{"{e["label"]}", 0x{e["addr"]:08X}, 0x{e["size"]:08X}, {e["hob"]}, '
          f'{e["rtype"]}, {e["rattr"]}, {e["mtype"]}, {e["armattr"]}}},\n')
    w("\n  // Register Regions\n")
    for e in registers:
        w(f'  {{"{e["label"]}", 0x{e["addr"]:08X}, 0x{e["size"]:08X}, {e["hob"]}, '
          f'{e["rtype"]}, {e["rattr"]}, {e["mtype"]}, {e["armattr"]}}},\n')
    w("};\n\n")
    w("""VOID
GetMemoryMap (
  OUT EFI_MEMORY_REGION_DESCRIPTOR **MemoryDescriptor,
  OUT UINT8                         *MemoryDescriptorCount)
{
  // Pass Data
  *MemoryDescriptor      = gMemoryDescriptor;
  *MemoryDescriptorCount = ARRAY_SIZE (gMemoryDescriptor);
}
""")
    return len(memory) + len(registers)


# Keys in [ConfigParameters] that are metadata or strings rather than platform
# parameters, and so must not appear in the UEFI configuration map. The string
# ones are already filtered out by the parser; these are the numeric ones that
# describe the file rather than the board.
CONFIG_META_KEYS = {
    "ConfigParameterCount",     # how many entries the vendor file has
}

# Values Mu-Silicium's ConfigMap expects that uefiplat.cfg does not spell out
# under a matching name. Kept explicit so their origin is visible.
CONFIG_EXTRA = [
    ("DetectRetailUserAttentionHotkey", 0x00),
    ("DetectRetailUserAttentionHotkeyCode", 0x17),
    ("EnableOEMSetupAppInRetail", 0x0),
    ("DDRInfoNotifyFlag", 0x1),
]


def emit_configmap(params, out):
    w = out.write
    w(LICENSE)
    w('#include <Library/ConfigurationMapLib.h>\n\n')
    w(GEN_NOTE)
    w("STATIC\nEFI_CONFIGURATION_ENTRY_DESCRIPTOR\ngConfigurationDescriptor[] = {\n")
    w("  // Configuration Map\n")
    n = 0
    for key, val in params:
        if key in CONFIG_META_KEYS:
            continue
        w(f'  {{"{key}", 0x{val:X}}},\n')
        n += 1
    w("  // added by the generator, not present verbatim in uefiplat.cfg\n")
    for key, val in CONFIG_EXTRA:
        w(f'  {{"{key}", 0x{val:X}}},\n')
        n += 1
    w("};\n\n")
    w("""VOID
GetConfigurationMap (
  OUT EFI_CONFIGURATION_ENTRY_DESCRIPTOR **ConfigurationDescriptor,
  OUT UINT8                               *ConfigurationDescriptorCount)
{
  // Pass Data
  *ConfigurationDescriptor      = gConfigurationDescriptor;
  *ConfigurationDescriptorCount = ARRAY_SIZE (gConfigurationDescriptor);
}
""")
    return n


