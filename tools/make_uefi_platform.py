# ---------------------------------------------------------------------------
# The three !include files the FDF pulls in.
#
# DXE.inc / APRIORI.inc list the drivers that go into the firmware volume, in
# load order. Almost every one of them is a Qualcomm binary that we extracted
# from this phone's own XBL, so the lists are the same ones the sibling board
# packages use - taken from the reference platform and rewritten to point at
# `Binaries/gauguin/`, then filtered down to the drivers we actually have.
#
# The filter is the important part: shipping an INF for a driver whose .efi is
# missing fails the FDF at build time, and shipping a driver we do not have a
# blob for would silently give us a firmware volume that does not match the
# hardware.

REF_PLATFORM = "surya"          # Xiaomi POCO X3 NFC / SM7150 - closest sibling

# Drivers this XBL carries that the surya reference package does not list, but
# which 16-51 other platform packages in the tree do. surya is an older SoC
# generation; the older ordering omits them. Taken from Xiaomi's aliothPkg
# (SM8250) instead, and inserted at the same anchor line alioth puts them after,
# so the relative load order is the reference's, not this generator's invention.
#
# PILDxe/PILProxyDxe are deliberately NOT inserted: the reference has PILDxe
# commented out, and they exist to load ADSP/CDSP firmware, which nothing in a
# Windows boot path consumes.
EXTRA_DRIVERS = {
    "DXE.inc": [
        ("Drivers/CmdDbDxe/CmdDbDxe.inf",       "PwrUtilsDxe"),
        ("Drivers/ClockDxe/ClockDxe.inf",       "VcsDxe"),
        ("Drivers/TLMMDxe/TLMMDxe.inf",         "FeatureEnablerDxe"),
        ("Drivers/CipherDxe/CipherDxe.inf",     "MacDxe"),
    ],
    "APRIORI.inc": [
        ("Drivers/CmdDbDxe/CmdDbDxe.inf",       "PwrUtilsDxe"),
        ("Drivers/PdcDxe/PdcDxe.inf",           "VcsDxe"),
        ("Universal/Variable/RuntimeDxe/VariableRuntimeDxe.inf", "FeatureEnablerDxe"),
        ("Drivers/CipherDxe/CipherDxe.inf",     "MacDxe"),
    ],
}

# Driver name -> path under Binaries/<device>/, for the EXTRA_DRIVERS entries.
EXTRA_PATHS = {
    "PwrUtilsDxe":      "QcomPkg/Drivers/PwrUtilsDxe/PwrUtilsDxe.inf",
    "VcsDxe":           "QcomPkg/Drivers/VcsDxe/VcsDxe.inf",
    "FeatureEnablerDxe": "QcomPkg/Drivers/FeatureEnablerDxe/FeatureEnablerDxe.inf",
    "MacDxe":           "QcomPkg/Drivers/MacDxe/MacDxe.inf",
}


def load_guid_table(mu_root):
    """Map RAW file name -> FILE FREEFORM GUID, from the whole Mu-Silicium tree.

    Qualcomm's panel and config files have fixed firmware-file GUIDs that every
    platform package in the tree reuses verbatim (verified: `uefipil.cfg` is
    21E9BDD9-... in surya, cepheus, vayu and marble alike). Reading them out of
    the tree beats inventing our own, because Qualcomm's own signed drivers are
    what look these files up.
    """
    table = {}
    for inc in glob.glob(os.path.join(mu_root, "Platforms/*/*/Include/RAW.inc")):
        text = open(inc, encoding="utf-8", errors="replace").read()
        for m in re.finditer(r'FILE FREEFORM = ([0-9A-Fa-f-]{36})\s*\{(.*?)\n\s*\}',
                             text, re.S):
            ui = re.search(r'SECTION UI = "([^"]+)"', m.group(2))
            if ui:
                table.setdefault(ui.group(1), m.group(1).upper())
    return table


def rewrite_incs(ref_dir, have, device):
    """Produce (dxe_inc, apriori_inc) for `device` from the reference package.

    `have` is the set of `QcomPkg/Drivers/.../*.inf` paths present under
    Binaries/<device>. Reference lines we cannot satisfy are commented out
    rather than dropped, so the gap stays visible in the generated file.
    """
    out = {}
    referenced = set()
    for name, key in (("DXE.inc", "dxe_inc"), ("APRIORI.inc", "apriori_inc")):
        src = os.path.join(ref_dir, "Include", name)
        text = open(src, encoding="utf-8", errors="replace").read()
        text = text.replace(f"Binaries/{REF_PLATFORM}/", f"Binaries/{device}/")

        lines, dropped = [], []
        for line in text.splitlines():
            m = re.match(r'^(\s*)INF Binaries/(\S+)', line)
            # `have` is keyed the way present_drivers() builds it - relative to
            # Binaries/<device>/ - so strip the device component the rename
            # above introduced before comparing.
            rel = m.group(2).split("/", 1)[1] if m and "/" in m.group(2) else None
            if m and rel not in have:
                dropped.append(m.group(2))
                lines.append(f"# dropped, no blob extracted from this XBL: {m.group(2)}")
                continue
            if m:
                referenced.add(rel)
            lines.append(line)

        # Insert the drivers surya's generation predates, at their alioth anchors.
        for anchor, name in EXTRA_DRIVERS.get(name, []):
            path = EXTRA_PATHS[name]
            if path not in have or path in referenced:
                continue
            idx = next((i for i, l in enumerate(lines) if anchor in l), None)
            if idx is None:
                dropped.append(f"{path}  (no anchor line for {anchor})")
                continue
            lines.insert(idx + 1, f"  INF Binaries/{device}/{path}")
            referenced.add(path)

        header = (f"##\n"
                  f"#  GENERATED by tools/make_uefi_platform.py from the\n"
                  f"#  {REF_PLATFORM}Pkg reference package - do not edit by hand.\n"
                  f"#\n"
                  f"#  Rewritten to Binaries/{device}/ and filtered to the drivers this\n"
                  f"#  project actually extracted from the device's own XBL.\n")
        if dropped:
            header += "#\n#  Not available (commented out below):\n"
            header += "".join(f"#    {d}\n" for d in sorted(set(dropped)))
        header += "##\n"
        out[key] = header + "\n".join(lines) + "\n"
        out[key + "_dropped"] = dropped
    out["referenced"] = referenced
    return out


def emit_raw_inc(raw_dir, guid_table, device):
    """Generate RAW.inc from the config and panel files we actually extracted.

    These are the FREEFORM files the firmware volume has to carry for Qualcomm's
    signed drivers to find their configuration: the UEFI PIL config, the charger
    and secure-partition configs, the boot menu, the boot logo, the battery
    indicator bitmaps, and the display panel descriptions.
    """
    names = sorted(f[:-4] for f in os.listdir(raw_dir) if f.endswith(".raw"))
    known, fresh = [], []
    for n in names:
        (known if n in guid_table else fresh).append(n)

    w = ["##",
         "#  GENERATED by tools/make_uefi_platform.py - do not edit by hand.",
         "#",
         f"#  {len(names)} FREEFORM files recovered from this device's XBL:",
         f"#    {len(known)} carry a GUID already used elsewhere in Mu-Silicium and are",
         "#       emitted with it, because Qualcomm's signed drivers look these files",
         "#       up by firmware-file GUID.",
         f"#    {len(fresh)} are not referenced by any existing platform package; their",
         "#       GUIDs are generated deterministically here. Nothing looks them up by",
         "#       GUID, so the value only has to be unique.",
         "##", ""]

    for n in names:
        if n in guid_table:
            guid, note = guid_table[n], ""
        else:
            guid, note = guid_for(n), "  # generated"
        w.append(f'  FILE FREEFORM = {guid} {{')
        w.append(f'    SECTION UI = "{n}"')
        w.append(f'    SECTION RAW = Binaries/{device}/RawFiles/{n}')
        w.append(f'  }}{note}')
        w.append("")
    return "\n".join(w).rstrip() + "\n"


def write_common(out_root, packagename, socinc, model):
    """Write the DSC/FDF/DEC/INC files a Mu-Silicium platform package needs."""
    pkg = os.path.join(out_root, "Platforms/Xiaomi", f"{packagename}Pkg")
    os.makedirs(os.path.join(pkg, "Include"), exist_ok=True)

    files = {
        f"{packagename}.dsc": model["dsc"],
        f"{packagename}.fdf": GAUGUIN_FDF,
        f"{packagename}.dec": GAUGUIN_DEC,
        "Include/DXE.inc": model["dxe_inc"],
        "Include/APRIORI.inc": model["apriori_inc"],
        "Include/RAW.inc": model["raw_inc"],
    }
    for name, text in files.items():
        with open(os.path.join(pkg, name), "w") as fh:
            fh.write(text)
    return pkg


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=REPO)
    ap.add_argument("--out", default=None,
                    help="where to write the packages (default: <repo>/uefi)")
    ap.add_argument("--dxe-dir", default=None,
                    help="extracted DXE drivers (default: <repo>/device/dxe)")
    ap.add_argument("--mu", default=None,
                    help="Mu-Silicium checkout (default: <repo>/work/uefi/Mu-Silicium)")
    args = ap.parse_args()

    cfg = os.path.join(args.repo, "device/config/uefiplat.cfg")
    if not os.path.isfile(cfg):
        sys.exit(f"missing {cfg}")
    out_root = args.out or os.path.join(args.repo, "uefi")
    dxe_dir = args.dxe_dir or os.path.join(args.repo, "device/dxe")
    mu_root = args.mu or os.path.join(args.repo, "work/uefi/Mu-Silicium")

    memory, registers, params = parse_uefiplat(cfg)
    print(f"uefiplat.cfg: {len(memory)} DDR regions, {len(registers)} register "
          f"regions, {len(params)} config parameters")

    soc = os.path.join(out_root, "Silicon/Qualcomm/BitraPkg")
    board = os.path.join(out_root, "Platforms/Xiaomi/gauguinPkg")
    for d in (os.path.join(soc, "Library/MemoryMapLib"),
              os.path.join(soc, "Library/PlatformSecLib"),
              os.path.join(soc, "Library/AcpiTableUpdateLib"),
              os.path.join(board, "Library/MemoryMapLib"),
              os.path.join(board, "Library/ConfigurationMapLib"),
              os.path.join(board, "Include"),
              os.path.join(out_root, "Binaries/gauguin/RawFiles"),
              os.path.join(out_root, "Resources/Configs")):
        os.makedirs(d, exist_ok=True)

    with open(os.path.join(soc, "BitraPkg.dsc.inc"), "w") as fh:
        fh.write(BITRA_DSC_INC.format(**SOC_DEFAULTS))
    print("wrote BitraPkg.dsc.inc")

    with open(os.path.join(board, "Library/MemoryMapLib/MemoryMapLib.c"), "w") as fh:
        n = emit_memmap(memory, registers, fh)
    print(f"wrote MemoryMapLib.c ({n} regions)")

    with open(os.path.join(board, "Library/ConfigurationMapLib/ConfigurationMapLib.c"), "w") as fh:
        n = emit_configmap(params, fh)
    print(f"wrote ConfigurationMapLib.c ({n} entries)")

    # The driver lists come from the reference package, filtered to the blobs we
    # actually extracted. Checked rather than assumed: an INF without a matching
    # .efi is a build failure, and a driver we lack is a hole in the firmware.
    if not os.path.isdir(dxe_dir):
        sys.exit(f"missing {dxe_dir} - run tools/xbl_extract.py first")
    have = present_drivers(dxe_dir)

    ref_dir = os.path.join(mu_root, "Platforms/Xiaomi", f"{REF_PLATFORM}Pkg")
    if not os.path.isdir(ref_dir):
        sys.exit(f"missing reference package {ref_dir}\n"
                 f"clone Mu-Silicium into {mu_root} first")
    model = rewrite_incs(ref_dir, have, "gauguin")

    guid_table = load_guid_table(mu_root)
    model["raw_inc"] = emit_raw_inc(dxe_dir, guid_table, "gauguin")
    model["dsc"] = GAUGUIN_DSC
    print(f"wrote DXE.inc / APRIORI.inc ({len(have)} drivers), "
          f"RAW.inc ({len(glob.glob(os.path.join(dxe_dir, '*.raw')))} files, "
          f"{len(guid_table)} GUIDs on file)")

    # Blobs we have but the reference lists never mention. Not a failure - the
    # reference is a different board - but each one is a driver that would be
    # silently left out of the firmware, so they are named rather than buried.
    orphans = sorted(have - model.pop("referenced"))
    if orphans:
        print(f"  {len(orphans)} blobs are packaged but not listed by the "
              f"{REF_PLATFORM} reference:")
        for o in orphans:
            print(f"    {o}")

    pkg = write_common(out_root, "gauguin", "BitraPkg/BitraPkg.dsc.inc", model)
    print(f"wrote platform package {pkg}")

    toml = os.path.join(out_root, "Resources/Configs/gauguin.toml")
    with open(toml, "w") as fh:
        fh.write(GAUGUIN_TOML)
    print(f"wrote {os.path.relpath(toml, out_root)}")

    print(f"\npackages written under {out_root}")
    print("next: tools/sync-uefi-platform.sh to install them into the Mu-Silicium tree")


if __name__ == "__main__":
    main()
