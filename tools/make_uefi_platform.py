def load_guid_table(mu_root):
    """Map RAW file name -> FILE FREEFORM GUID, from the whole Mu-Silicium tree.

    Qualcomm's panel and config files have fixed firmware-file GUIDs that every
    platform package in the tree reuses verbatim (verified: `uefipil.cfg` is
    21E9BDD9-... in surya, cepheus, vayu and marble alike). Reading them out of
    the tree beats inventing our own, because Qualcomm's own signed drivers are
    what look these files up.
    """
    table = {}
    for inc in glob.glob(os.path.join(mu_root, "Platforms/*/*/Include/RAW.inc")):
        text = open(inc, encoding="utf-8", errors="replace").read()
        for m in re.finditer(r'FILE FREEFORM = ([0-9A-Fa-f-]{36})\s*\{(.*?)\n\s*\}',
                             text, re.S):
            ui = re.search(r'SECTION UI = "([^"]+)"', m.group(2))
            if ui:
                table.setdefault(ui.group(1), m.group(1).upper())
    return table


def apply_apriori_moves(lines, moves):
    """Move the named INF lines of APRIORI.inc to just after an anchor line.

    `moves` is a list of (anchor, [name, ...]); anchor and names are substrings
    of `INF ...` lines. Nothing is added or removed, only reordered, so the
    firmware volume keeps the same files at the same offsets and the only byte
    that changes is the Apriori GUID array itself.

    Every name has to match exactly one line. A name that matches none would
    otherwise move nothing and read, in a build log, exactly like an experiment
    that ran; a name that matches two would silently move whichever came first.
    Both are exit conditions rather than warnings.

    Returns [(anchor, path), ...] for the report and for the generated header.
    """
    report = []
    for anchor, names in moves:
        anchor_at = [i for i, l in enumerate(lines)
                     if anchor in l and l.strip().startswith("INF")]
        if len(anchor_at) != 1:
            sys.exit(f"--apriori-move: anchor {anchor!r} matches "
                     f"{len(anchor_at)} INF lines in APRIORI.inc, want 1")
        src = []
        for name in names:
            at = [i for i, l in enumerate(lines)
                  if name in l and l.strip().startswith("INF")]
            if len(at) != 1:
                sys.exit(f"--apriori-move: {name!r} matches {len(at)} INF lines "
                         f"in APRIORI.inc, want 1")
            if at[0] == anchor_at[0]:
                sys.exit(f"--apriori-move: {name!r} is the anchor line {anchor!r}")
            src.append(at[0])
        if len(set(src)) != len(src):
            sys.exit(f"--apriori-move: two names under anchor {anchor!r} match "
                     f"the same line")

        picked = [lines[i] for i in src]
        # Where the anchor ends up once the moved lines are gone from in front of
        # it. Removing and re-inserting in one pass would need the indices
        # rewritten anyway, so they are rewritten once, here.
        after = anchor_at[0] - len([i for i in src if i < anchor_at[0]])
        for i in sorted(src, reverse=True):
            del lines[i]
        for offset, line in enumerate(picked):
            lines.insert(after + 1 + offset, line)
            report.append((anchor, line.strip().removeprefix("INF ")))
    return report


def rewrite_incs(ref_dir, have, device, apriori_moves=(), xhci_host=False):
    """Produce (dxe_inc, apriori_inc) for `device` from the reference package.

    `have` is the set of `QcomPkg/Drivers/.../*.inf` paths present under
    Binaries/<device>. Reference lines we cannot satisfy are commented out
    rather than dropped, so the gap stays visible in the generated file.

    `apriori_moves` reorders APRIORI.inc only, and only when asked for; the
    default output is byte-for-byte the reference order.

    `xhci_host` adds the USB host stack (see XHCI_HOST_DRIVERS). Off by default,
    which is also what keeps a regeneration of an existing tree byte-identical.
    """
    out = {}
    referenced = set()
    for name, key in (("DXE.inc", "dxe_inc"), ("APRIORI.inc", "apriori_inc")):
        src = os.path.join(ref_dir, "Include", name)
        text = open(src, encoding="utf-8", errors="replace").read()
        text = text.replace(f"Binaries/{REF_PLATFORM}/", f"Binaries/{device}/")

        lines, dropped = [], []
        for line in text.splitlines():
            m = re.match(r'^(\s*)INF Binaries/(\S+)', line)
            # `have` is keyed the way present_drivers() builds it - relative to
            # Binaries/<device>/ - so strip the device component the rename
            # above introduced before comparing.
            rel = m.group(2).split("/", 1)[1] if m and "/" in m.group(2) else None
            if m and rel not in have:
                dropped.append(m.group(2))
                lines.append(f"# dropped, no blob extracted from this XBL: {m.group(2)}")
                continue
            if m:
                referenced.add(rel)
            lines.append(line)

        # Insert the drivers surya's generation predates, at their alioth anchors.
        for anchor, extra in EXTRA_DRIVERS.get(name, []):
            path = EXTRA_PATHS[extra]
            if path not in have or path in referenced:
                continue
            idx = next((i for i, l in enumerate(lines) if anchor in l), None)
            if idx is None:
                dropped.append(f"{path}  (no anchor line for {anchor})")
                continue
            lines.insert(idx + 1, f"  INF Binaries/{device}/{path}")
            referenced.add(path)

        # The USB host stack, in a conditional rather than inserted outright, so
        # the switch lives in the DSC next to USE_CUSTOM_DISPLAY_DRIVER and the
        # default build cannot acquire it by regenerating.
        uhci, xhci_dropped = [], []
        if xhci_host:
            for anchor, paths in XHCI_HOST_DRIVERS.get(name, []):
                present = [p for p in paths if p in have]
                if not present:
                    missing = f"{paths[0]}  (no blob staged for it)"
                    dropped.append(missing)
                    xhci_dropped.append(missing)
                    continue
                idx = next((i for i, l in enumerate(lines) if anchor in l), None)
                if idx is None:
                    anchorless = f"{present[0]}  (no anchor line for {anchor})"
                    dropped.append(anchorless)
                    xhci_dropped.append(anchorless)
                    continue
                lines[idx + 1:idx + 1] = (
                    [f"!if $({XHCI_HOST_GUARD}) == 1"]
                    + [f"  INF Binaries/{device}/{p}" for p in present]
                    + ["!endif"])
                referenced.update(present)
                uhci += present

        # Reordering is APRIORI.inc's alone. DXE.inc decides which FFS files the
        # volume carries and where they land, and reordering it would move every
        # offset in the map that tools/fv-inventory.py checks against.
        moved = []
        if name == "APRIORI.inc" and apriori_moves:
            moved = apply_apriori_moves(lines, apriori_moves)

        # Nothing in the reference lists these, so they would be packaged and
        # then silently left out of the firmware volume. Naming them in the file
        # keeps that visible after the generator's stdout is long gone.
        skipped = sorted(have - referenced - set(out.get("orphans_seen", set())))

        header = (f"##\n"
                  f"#  GENERATED by tools/make_uefi_platform.py from the\n"
                  f"#  {REF_PLATFORM}Pkg reference package - do not edit by hand.\n"
                  f"#\n"
                  f"#  Rewritten to Binaries/{device}/ and filtered to the drivers this\n"
                  f"#  project actually extracted from the device's own XBL.\n")
        if moved:
            header += ("#\n"
                       "#  EXPERIMENT - NOT the reference order. --apriori-move was used,\n"
                       "#  so the a-priori batch runs in the order below, not surya's:\n")
            header += "".join(f"#    {path}\n#      moved to just after {anchor}\n"
                              for anchor, path in moved)
            header += ("#  Regenerate without --apriori-move to restore the reference\n"
                       "#  order. Which one the device ran is recorded by\n"
                       "#  tools/build-apriori-variant.sh.\n")
        if uhci:
            header += ("#\n"
                       "#  --xhci-host: this file also carries the USB host stack, in\n"
                       f"#  `!if $({XHCI_HOST_GUARD}) == 1` above. Those blobs are the\n"
                       f"#  ONE exception to the sentence above - they came from\n"
                       f"#  Binaries/{SIBLING_SOURCE}/, not from this device, because this\n"
                       "#  device's XBL has no host-controller driver to extract. See\n"
                       "#  SIBLING_BLOBS in tools/make_xbl_binaries.py.\n")
            header += "".join(f"#    {p}\n" for p in uhci)
        if dropped:
            header += "#\n#  Not available (commented out below):\n"
            header += "".join(f"#    {d}\n" for d in sorted(set(dropped)))
        if skipped and name == "DXE.inc":
            header += ("#\n"
                       "#  Packaged under Binaries/gauguin/ but NOT in this file, so not in\n"
                       "#  the firmware volume. The reference has no line for them. Add an\n"
                       "#  INF line if any turns out to be needed:\n")
            header += "".join(f"#    {s}\n" for s in skipped)
        header += "##\n"
        out[key] = header + "\n".join(lines) + "\n"
        out[key + "_dropped"] = dropped
        out["orphans_seen"] = set(skipped)
        if moved:
            out["apriori_moved"] = moved
        if uhci:
            out.setdefault("xhci_host", []).extend(uhci)
        if xhci_dropped:
            out.setdefault("xhci_dropped", []).extend(xhci_dropped)
    out.pop("orphans_seen", None)
    out["referenced"] = referenced
    return out


def emit_raw_inc(raw_dir, guid_table, device):
    """Generate RAW.inc from the config and panel files we actually extracted.

    These are the FREEFORM files the firmware volume has to carry for Qualcomm's
    signed drivers to find their configuration: the UEFI PIL config, the charger
    and secure-partition configs, the boot menu, the boot logo, the battery
    indicator bitmaps, and the display panel descriptions.
    """
    names = sorted(f[:-4] for f in os.listdir(raw_dir) if f.endswith(".raw"))
    known, fresh = [], []
    for n in names:
        (known if n in guid_table else fresh).append(n)

    w = ["##",
         "#  GENERATED by tools/make_uefi_platform.py - do not edit by hand.",
         "#",
         f"#  {len(names)} FREEFORM files recovered from this device's XBL:",
         f"#    {len(known)} carry a GUID already used elsewhere in Mu-Silicium and are",
         "#       emitted with it, because Qualcomm's signed drivers look these files",
         "#       up by firmware-file GUID.",
         f"#    {len(fresh)} are not referenced by any existing platform package; their",
         "#       GUIDs are generated deterministically here. Nothing looks them up by",
         "#       GUID, so the value only has to be unique.",
         "##", ""]

    for n in names:
        if n in guid_table:
            guid, note = guid_table[n], ""
        else:
            guid, note = guid_for(n), "  # generated"
        w.append(f'  FILE FREEFORM = {guid} {{')
        w.append(f'    SECTION UI = "{n}"')
        w.append(f'    SECTION RAW = Binaries/{device}/RawFiles/{n}')
        w.append(f'  }}{note}')
        w.append("")
    return "\n".join(w).rstrip() + "\n"


def emit_devicebuild(ref_dir, device, packagename):
    """Produce DeviceBuild.py from the reference package.

    This file is almost entirely boilerplate that names the device: the
    platform DSC path, the package name, the build scope, PRODUCT_NAME. The
    reference and this board differ in nothing else, so rather than copy it by
    hand and let the two drift, it is derived.
    """
    src = os.path.join(ref_dir, "DeviceBuild.py")
    text = open(src, encoding="utf-8").read()
    text = text.replace(REF_PLATFORM, device).replace(REF_PLATFORM.capitalize(),
                                                      device.capitalize())
    header = (f"##\n"
              f"#  GENERATED by tools/make_uefi_platform.py from\n"
              f"#  {REF_PLATFORM}Pkg/DeviceBuild.py - do not edit by hand.\n"
              f"#\n"
              f"#  Differs from the reference only in the device name.\n"
              f"##\n")
    # The reference already opens with its own licence banner; keep it, but put
    # this note above so the file does not look hand-written.
    return header + text, text.count(f'"{device}')


