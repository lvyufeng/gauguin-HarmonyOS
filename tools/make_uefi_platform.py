"""Generate the UEFI platform package for gauguin from Qualcomm's own config.

The two libraries a Mu-Silicium platform package has to provide are pure data:

  MemoryMapLib        the DDR and MMIO map UEFI is told about
  ConfigurationMapLib the platform tuning parameters

Both are exactly what the phone's XBL already carries in `uefiplat.cfg`, which
this project extracted into `device/config/`. So instead of hand-transcribing
~80 memory regions (and getting one wrong in a way that only shows up as a hang),
this reads Qualcomm's own numbers and emits the C.

Reference packages for the surrounding boilerplate: `MooreaPkg` (SM7150) at the
SoC level and `suryaPkg` (Xiaomi POCO X3 NFC) at the board level.

Usage:  make_uefi_platform.py [--repo DIR]
"""
